# Testi che non sono chiavi (simboli SF, percorsi costruiti, verbatim).
IGNORE_RE = re.compile(r'^[a-z0-9.]+$|^ftp://|^\\\(base\)|^\\\(Format|^\\\(n\)$')

PAT = re.compile(r'(?:\bL\(|Text\(|Button\(|Label\(|Toggle\(|Section\(|TextField\(|SecureField\(|Menu\(|TableColumn\(|confirmationDialog\(|FieldRow\(|Picker\(|\.help\(|prompt: Text\(|return |LocalizedStringKey = )\s*"((?:[^"\\]|\\.)*)"')

def swiftui_key(s):
    # \(x) → %@ o %lld secondo un'euristica sul nome (count/n/numeri → %lld).
    def rep(m):
        e = m.group(1)
        return '%lld' if re.search(r'count|\bn\b|Int\(|percent', e) else '%@'
    if '\\(' in s:
        s = s.replace('%', '%%')
    return re.sub(r'\\\(([^()]*(?:\([^()]*\))?[^()]*)\)', rep, s)

def keys_in_code():
    keys = set()
    for f in glob.glob(os.path.join(ROOT, 'Sources/Mirrorpress/*.swift')):
        for m in PAT.finditer(open(f).read()):
            k = m.group(1)
            if not re.search('[A-Za-zàèéìòù]', k) or IGNORE_RE.search(k):
                continue
            keys.add(swiftui_key(k).replace('\\"', '"'))
    return keys

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

def main():
    for lang, header, table in (("it", "/* Mirrorpress: Italiano. Le chiavi sono già i testi italiani. */", {k: k for k in EN}),
                                ("en", "/* Mirrorpress: English. Keys are the Italian source texts. */", EN)):
        path = os.path.join(ROOT, f'Resources/{lang}.lproj/Localizable.strings')
        with open(path, 'w') as f:
            f.write(header + "\n")
            for k in EN:
                f.write(f'"{esc(k)}" = "{esc(table[k])}";\n')
    missing = sorted(k for k in keys_in_code() if k not in EN)
    for k in missing:
        print("MANCA:", k)
    print(f"{len(EN)} traduzioni scritte, {len(missing)} mancanti")
    sys.exit(1 if missing else 0)

main()
